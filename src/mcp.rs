/// MCP server over the shared [`Service`].
///
/// # Examples
///
/// ```
/// use std::sync::Arc;
/// use njt_mcp::{Config, NjtServer, Service};
/// let dir = std::env::temp_dir().join(format!("njt-mcp-server-{}", std::process::id()));
/// let config = Config::parse([
///     ("NJT_TOKEN", "replace-me"),
///     ("NJT_CACHE_DIR", dir.to_str().unwrap()),
/// ])
/// .unwrap();
/// let server = NjtServer::new(Arc::new(Service::new(config).unwrap()));
/// assert_eq!(server.service().status()["credential_mode"], "token");
/// let _ = std::fs::remove_dir_all(&dir);
/// ```
#[derive(Clone)]
pub struct NjtServer {
    /// Shared NJ Transit client.
    service: Arc<Service>,
    /// Tool router generated by `rmcp`.
    tool_router: ToolRouter<Self>,
}

impl NjtServer {
    /// Wrap a service. The tool list is fixed at compile time.
    ///
    /// # Arguments
    ///
    /// * `service` - shared service.
    ///
    /// # Returns
    ///
    /// A server that can be cloned per HTTP session.
    ///
    /// # Panics
    ///
    /// This function does not panic.
    ///
    /// # Examples
    ///
    /// ```
    /// use std::sync::Arc;
    /// use njt_mcp::{Config, NjtServer, Service};
    /// let dir = std::env::temp_dir().join(format!("njt-mcp-server-new-{}", std::process::id()));
    /// let config = Config::parse([
    ///     ("NJT_TOKEN", "replace-me"),
    ///     ("NJT_CACHE_DIR", dir.to_str().unwrap()),
    /// ])
    /// .unwrap();
    /// let _server = NjtServer::new(Arc::new(Service::new(config).unwrap()));
    /// let _ = std::fs::remove_dir_all(&dir);
    /// ```
    pub fn new(service: Arc<Service>) -> Self {
        Self {
            service,
            tool_router: Self::tool_router(),
        }
    }

    /// Borrow the service.
    ///
    /// # Returns
    ///
    /// The shared [`Service`].
    ///
    /// # Panics
    ///
    /// This function does not panic.
    ///
    /// # Examples
    ///
    /// ```
    /// use std::sync::Arc;
    /// use njt_mcp::{Config, NjtServer, Service};
    /// let dir = std::env::temp_dir().join(format!("njt-mcp-server-svc-{}", std::process::id()));
    /// let config = Config::parse([
    ///     ("NJT_TOKEN", "replace-me"),
    ///     ("NJT_CACHE_DIR", dir.to_str().unwrap()),
    /// ])
    /// .unwrap();
    /// let server = NjtServer::new(Arc::new(Service::new(config).unwrap()));
    /// assert!(server.service().status()["mints"].is_object());
    /// let _ = std::fs::remove_dir_all(&dir);
    /// ```
    pub fn service(&self) -> &Service {
        &self.service
    }
}

