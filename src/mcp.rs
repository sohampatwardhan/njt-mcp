/// Serve one stdio session. Logs stay on stderr.
///
/// # Arguments
///
/// * `server` - constructed server.
///
/// # Errors
///
/// Returns [`AppError`] when stdio setup or the session fails.
///
/// # Panics
///
/// This function does not panic.
///
/// # Examples
///
/// ```no_run
/// use std::sync::Arc;
/// use njt_mcp::{serve_stdio, Config, NjtServer, Service};
/// # async fn demo() -> Result<(), njt_mcp::AppError> {
/// let config = Config::parse([
///     ("NJT_TOKEN", "replace-me"),
///     ("NJT_CACHE_DIR", "/tmp/njt-mcp-doctest"),
/// ]).expect("config");
/// serve_stdio(NjtServer::new(Arc::new(Service::new(config)?))).await
/// # }
/// ```
pub async fn serve_stdio(server: NjtServer) -> Result<(), AppError> {
    let running = server
        .serve(rmcp::transport::stdio())
        .await
        .map_err(|error| AppError::new(format!("stdio: {error}")))?;
    running
        .waiting()
        .await
        .map_err(|error| AppError::new(format!("stdio: {error}")))?;
    Ok(())
}

/// Serve streamable HTTP until Ctrl-C.
///
/// MCP is at `/mcp`. Liveness is `GET /healthz`.
///
/// # Arguments
///
/// * `service` - shared service.
/// * `bind` - socket address.
/// * `allowed_hosts` - extra Host headers. Localhost is always allowed by the SDK default when this list is empty.
///
/// # Errors
///
/// Returns [`AppError`] when the socket cannot be bound or the server stops with an error.
///
/// # Panics
///
/// This function does not panic.
///
/// # Examples
///
/// ```no_run
/// use std::sync::Arc;
/// use njt_mcp::{serve_http, Config, Service};
/// # async fn demo() -> Result<(), njt_mcp::AppError> {
/// let config = Config::parse([
///     ("NJT_TOKEN", "replace-me"),
///     ("NJT_CACHE_DIR", "/tmp/njt-mcp-doctest"),
/// ]).expect("config");
/// let bind = "127.0.0.1:8092".parse().unwrap();
/// serve_http(Arc::new(Service::new(config)?), bind, Vec::new()).await
/// # }
/// ```
pub async fn serve_http(
    service: Arc<Service>,
    bind: SocketAddr,
    allowed_hosts: Vec<String>,
) -> Result<(), AppError> {
    let listener = tokio::net::TcpListener::bind(bind)
        .await
        .map_err(|error| AppError::new(format!("bind {bind}: {error}")))?;
    let addr = listener
        .local_addr()
        .map_err(|error| AppError::new(format!("local address: {error}")))?;
    tracing::info!("njt-mcp listening on http://{addr}/mcp");
    let router = http_router(service, allowed_hosts);
    axum::serve(listener, router)
        .with_graceful_shutdown(async {
            let _ = tokio::signal::ctrl_c().await;
        })
        .await
        .map_err(|error| AppError::new(format!("http: {error}")))?;
    Ok(())
}

/// Bind an HTTP server on a background task.
///
/// # Arguments
///
/// * `service` - shared service.
/// * `bind` - socket address. Port 0 asks the OS for a free port.
/// * `allowed_hosts` - extra Host headers.
///
/// # Returns
///
/// The bound address and the server task.
///
/// # Errors
///
/// Returns [`AppError`] when the socket cannot be bound.
///
/// # Panics
///
/// This function does not panic.
///
/// # Examples
///
/// ```no_run
/// use std::sync::Arc;
/// use njt_mcp::{spawn_http, Config, Service};
/// # async fn demo() -> Result<(), njt_mcp::AppError> {
/// let config = Config::parse([
///     ("NJT_TOKEN", "replace-me"),
///     ("NJT_CACHE_DIR", "/tmp/njt-mcp-doctest"),
/// ]).expect("config");
/// let (addr, handle) = spawn_http(Arc::new(Service::new(config)?), "127.0.0.1:0".parse().unwrap(), Vec::new()).await?;
/// let _ = (addr, handle);
/// # Ok(())
/// # }
/// ```
pub async fn spawn_http(
    service: Arc<Service>,
    bind: SocketAddr,
    allowed_hosts: Vec<String>,
) -> Result<(SocketAddr, tokio::task::JoinHandle<()>), AppError> {
    let listener = tokio::net::TcpListener::bind(bind)
        .await
        .map_err(|error| AppError::new(format!("bind {bind}: {error}")))?;
    let addr = listener
        .local_addr()
        .map_err(|error| AppError::new(format!("local address: {error}")))?;
    let router = http_router(service, allowed_hosts);
    let handle = tokio::spawn(async move {
        let _ = axum::serve(listener, router).await;
    });
    Ok((addr, handle))
}

/// Axum router with /healthz and the streamable HTTP MCP service.
///
/// # Arguments
///
/// * `service` - see the signature.
/// * `allowed_hosts` - see the signature.
///
/// # Returns
///
/// The value described above.
///
/// # Panics
///
/// This function does not panic.
///
/// # Examples
///
/// Used by the surrounding module. Doctests cover the public wrappers.
fn http_router(service: Arc<Service>, allowed_hosts: Vec<String>) -> axum::Router {
    let mut config = StreamableHttpServerConfig::default()
        .with_legacy_session_mode(false)
        .with_json_response(true);
    if !allowed_hosts.is_empty() {
        config = config.with_allowed_hosts(allowed_hosts);
    }
    let http = StreamableHttpService::new(
        {
            let service = Arc::clone(&service);
            move || Ok(NjtServer::new(Arc::clone(&service)))
        },
        Arc::new(LocalSessionManager::default()),
        config,
    );
    axum::Router::new()
        .route("/healthz", axum::routing::get(|| async { "ok" }))
        .nest_service("/mcp", http)
}

